// app/api/admin/studio-model/test/route.ts
import { NextRequest, NextResponse } from "next/server";
import { verifyToken, isAdminUser } from "@/lib/auth";
import { openRouterChat } from "@/lib/openrouter";
import { getActiveLlmModelName } from "@/lib/ai/modelRouter";
import { recordTokenUsage } from "@/lib/agent-studio/dbStore";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * POST /api/admin/studio-model/test
 * Interactive live model test console endpoint.
 * Sends a test prompt to the LLM, measures execution latency,
 * records tokens, and returns detailed diagnostic metrics.
 */
export async function POST(req: NextRequest) {
  const startTime = Date.now();
  try {
    const token = req.cookies.get("token")?.value || req.cookies.get("auth_token")?.value;
    const payload: any = token ? verifyToken(token) : null;
    if (!payload || !isAdminUser(payload)) {
      return NextResponse.json(
        { success: false, error: "Unauthorized", message: "Admin access required" },
        { status: 401 }
      );
    }

    const body = await req.json().catch(() => ({}));
    const prompt = String(body.prompt || "Hello! Provide a 1-sentence verification of your model name and reasoning capability.").trim();
    const requestedModel = body.model_name ? String(body.model_name).trim() : await getActiveLlmModelName();

    const messages = [
      {
        role: "system" as const,
        content: "You are CreditWise AI's central reasoning engine. Respond concisely, accurately, and professionally to this diagnostic test query.",
      },
      {
        role: "user" as const,
        content: prompt,
      },
    ];

    // Call LLM
    const llmRes = await openRouterChat(messages, undefined, requestedModel);
    const latencyMs = Date.now() - startTime;

    const reply = llmRes?.choices?.[0]?.message?.content || "No response text generated by model.";
    const usage = {
      promptTokens: Number(llmRes?.usage?.prompt_tokens || Math.max(10, Math.ceil(prompt.length / 4))),
      completionTokens: Number(llmRes?.usage?.completion_tokens || Math.max(10, Math.ceil(reply.length / 4))),
      totalTokens: Number(llmRes?.usage?.total_tokens || 0),
    };
    if (usage.totalTokens === 0) {
      usage.totalTokens = usage.promptTokens + usage.completionTokens;
    }

    // Record token usage in database
    try {
      await recordTokenUsage({
        agentId: "model_diagnostic",
        agentName: "Model Console",
        modelName: requestedModel,
        promptTokens: usage.promptTokens,
        completionTokens: usage.completionTokens,
        totalTokens: usage.totalTokens,
        source: "playground",
      });
    } catch (tErr) {
      console.warn("[MODEL_TEST_TOKEN_WARN]", tErr);
    }

    return NextResponse.json({
      success: true,
      reply,
      latencyMs,
      usage,
      modelName: requestedModel,
      provider: requestedModel.includes("nvidia")
        ? "Nvidia"
        : requestedModel.includes("deepseek")
        ? "DeepSeek"
        : requestedModel.includes("gemini")
        ? "Google"
        : requestedModel.includes("gpt")
        ? "OpenAI"
        : requestedModel.includes("claude")
        ? "Anthropic"
        : "OpenRouter",
      timestamp: new Date().toISOString(),
      raw: {
        id: llmRes?.id,
        model: llmRes?.model || requestedModel,
        finish_reason: llmRes?.choices?.[0]?.finish_reason,
      },
    });
  } catch (err: any) {
    const latencyMs = Date.now() - startTime;
    console.error("POST /api/admin/studio-model/test error:", err);
    return NextResponse.json(
      {
        success: false,
        error: "Execution Failure",
        message: err?.message || "Failed to execute model test",
        latencyMs,
      },
      { status: 500 }
    );
  }
}
